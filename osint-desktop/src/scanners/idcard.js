const ZODIAC = ['鼠', '牛', '虎', '兔', '龙', '蛇', '马', '羊', '猴', '鸡', '狗', '猪'];

function calcZodiac(year) {
  return ZODIAC[(year - 4) % 12];
}

function calcConstellation(month, day) {
  const edges = [
    [1, 20, '水瓶座'], [2, 19, '双鱼座'], [3, 21, '白羊座'], [4, 20, '金牛座'],
    [5, 21, '双子座'], [6, 22, '巨蟹座'], [7, 23, '狮子座'], [8, 23, '处女座'],
    [9, 23, '天秤座'], [10, 24, '天蝎座'], [11, 23, '射手座'], [12, 22, '摩羯座'],
  ];
  for (const [m, d, name] of edges) {
    if (month < m || (month === m && day < d)) {
      // 找到第一个未到的边界，前一个星座
      return name;
    }
  }
  return '摩羯座';
}

// 校验 18 位身份证（ISO 7064 MOD 11-2）
function isValidID(id) {
  if (!/^\d{17}[\dXx]$/.test(id)) return false;
  const weights = [7, 9, 10, 5, 8, 4, 2, 1, 6, 3, 7, 9, 10, 5, 8, 4, 2];
  const codes = '10X98765432';
  let sum = 0;
  for (let i = 0; i < 17; i++) sum += parseInt(id[i], 10) * weights[i];
  return codes[sum % 11] === id[17].toUpperCase();
}

class IDCardScanner extends Scanner {
  constructor() {
    super('idcard');
  }

  canHandle(input) {
    const v = (input || '').trim();
    return /^\d{15}$/.test(v) || /^\d{17}[\dXx]$/.test(v);
  }

  async scan(input) {
    const id = input.trim().toUpperCase();
    const is18 = id.length === 18;
    const valid = is18 ? isValidID(id) : null; // 15 位无法校验位

    const provinceCode = id.substring(0, 2);
    const cityCode = id.substring(0, 4);
    const regionCode = id.substring(0, 6);

    const birthRaw = is18 ? id.substring(6, 14) : '19' + id.substring(6, 12);
    const year = parseInt(birthRaw.substring(0, 4), 10);
    const month = parseInt(birthRaw.substring(4, 6), 10);
    const day = parseInt(birthRaw.substring(6, 8), 10);

    const genderCode = is18 ? parseInt(id[16], 10) : parseInt(id[14], 10);
    const gender = genderCode % 2 === 1 ? '男' : '女';

    const now = new Date();
    const age = now.getFullYear() - year - (now.getMonth() + 1 < month || (now.getMonth() + 1 === month && now.getDate() < day) ? 1 : 0);

    return {
      source: 'idcard',
      valid: is18 ? valid : 'unknown(15位)',
      data: {
        regionCode,
        province: PROVINCES[provinceCode] || '未知',
        city: CITIES[cityCode] || '未知',
        birth: `${year}-${String(month).padStart(2, '0')}-${String(day).padStart(2, '0')}`,
        age,
        gender,
        zodiac: calcZodiac(year),
        constellation: calcConstellation(month, day),
        checkDigitValid: is18 ? valid : 'unknown',
      },
    };
  }
}

